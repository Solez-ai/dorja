        "bn" -> BN
        "hi" -> HI
        "zh" -> ZH
        "ko" -> KO
        "de" -> DE
        "fr" -> FR
        "ar" -> AR
        "es" -> ES
        "ru" -> RU
        "tr" -> TR
        "th" -> TH
        "vi" -> VI
        "it" -> IT
        "ur" -> UR
        "pt" -> PT
        "nl" -> NL
        "pl" -> PL
        "ms" -> MS
        "tl" -> TL
        "ne" -> NE
        else -> emptyMap()
    }

